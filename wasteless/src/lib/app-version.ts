export async function applyAppUpdate(): Promise<void> {
  if (typeof window === "undefined") return;

  let activatedWaiting = false;

  try {
    if ("serviceWorker" in navigator) {
      const reg = await navigator.serviceWorker.getRegistration();
      if (reg) {
        try {
          await reg.update();
        } catch {
          /* ignore */
        }

        const waiting =
          reg.waiting ??
          (await navigator.serviceWorker.getRegistration())?.waiting ??
          null;

        if (waiting) {
          activatedWaiting = await activateWaitingWorker(waiting);
        } else if (reg.installing) {
          activatedWaiting = await waitForInstallThenActivate(reg);
        }
      }

      // No waiting worker to activate (stale registration / first migration):
      // drop registrations and Cache Storage so the reload is network-fresh.
      if (!activatedWaiting) {
        const regs = await navigator.serviceWorker.getRegistrations();
        await Promise.all(
          regs.map(async (r) => {
            try {
              await r.unregister();
            } catch {
              /* ignore */
            }
          })
        );
        if ("caches" in window) {
          const keys = await caches.keys();
          await Promise.all(keys.map((key) => caches.delete(key)));
        }
      }
    }
  } catch {
    /* ignore */
  }

  const url = new URL(window.location.href);
  url.searchParams.set("_v", String(Date.now()));
  window.location.replace(url.toString());
}

function activateWaitingWorker(waiting: ServiceWorker): Promise<boolean> {
  return new Promise((resolve) => {
    let settled = false;
    const done = (ok: boolean) => {
      if (settled) return;
      settled = true;
      resolve(ok);
    };

    const onChange = () => {
      navigator.serviceWorker.removeEventListener("controllerchange", onChange);
      done(true);
    };
    navigator.serviceWorker.addEventListener("controllerchange", onChange);
    waiting.postMessage({ type: "SKIP_WAITING" });
    window.setTimeout(() => {
      navigator.serviceWorker.removeEventListener("controllerchange", onChange);
      // Message was delivered; even without controllerchange, reload next.
      done(true);
    }, 2000);
  });
}

function waitForInstallThenActivate(
  reg: ServiceWorkerRegistration
): Promise<boolean> {
  return new Promise((resolve) => {
    const worker = reg.installing;
    if (!worker) {
      resolve(false);
      return;
    }
    let settled = false;
    const finish = (ok: boolean) => {
      if (settled) return;
      settled = true;
      resolve(ok);
    };

    worker.addEventListener("statechange", () => {
      if (worker.state === "installed" && reg.waiting) {
        void activateWaitingWorker(reg.waiting).then(finish);
      }
      if (worker.state === "activated") finish(true);
    });
    window.setTimeout(() => finish(false), 2500);
  });
}
